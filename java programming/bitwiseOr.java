public class bitwiseOr {
    public static void main(String[] args) {
        int a = 4; // binary: 0100
        int b = 8; // binary: 1000
        int result = a | b; // binary: 1100, decimal: 12
        System.out.println("The result of bitwise OR operation between " + a + " and " + b + " is : " + result);
    }
}
