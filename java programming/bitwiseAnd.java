public class bitwiseAnd {
    public static void main(String[] args) {
        int a = 5; // binary: 0101
        int b = 3; // binary: 0011
        int result = a & b; // binary: 0001, decimal: 1
        System.out.println("The result of bitwise AND operation between " + a + " and " + b + " is: " + result);
    }
}
